"""Compile the authored depth-pair compute shader without game input."""
import argparse,hashlib,struct,subprocess,tempfile
from pathlib import Path

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--compiler',type=Path,required=True);args=parser.parse_args()
    root=Path(__file__).resolve().parent;source=root/'shaders/depth_pair_reproject.comp'
    with tempfile.TemporaryDirectory(prefix='hookshot-vr-depth-pair-') as directory:
        output=Path(directory)/'depth.spv';subprocess.run([str(args.compiler),'-V','--target-env','vulkan1.2','-o',str(output),str(source)],check=True);data=output.read_bytes()
    if not data or len(data)%4 or len(data)>65536:raise ValueError('Authored shader size outside bounds')
    words=struct.unpack('<'+'I'*(len(data)//4),data);assert words[0]==0x07230203
    text='// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by vr/generate_depth_pair_shader.py; edit the authored .comp source.\n'
    text+='// Source SHA256: '+hashlib.sha256(source.read_bytes().replace(b'\r\n',b'\n')).hexdigest()+'\n#pragma once\n#include <cstdint>\ninline constexpr uint32_t kDepthPairReprojectSpv[]={\n'
    text+=''.join('    '+','.join(f'0x{w:08x}' for w in words[i:i+8])+',\n' for i in range(0,len(words),8))+'};\n'
    (root/'src/depth_pair_reproject_spv.h').write_text(text,encoding='utf-8',newline='\n')
if __name__=='__main__':main()
