"""Compile authored XR calibration shaders; no game shader is read."""
import argparse,hashlib,struct,subprocess,tempfile
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('--compiler',type=Path,required=True);args=p.parse_args();root=Path(__file__).resolve().parent
with tempfile.TemporaryDirectory() as temporary:
    text='// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by vr/generate_depth_scene_shaders.py\n#pragma once\n#include <cstdint>\n'
    for stage in ('vert','frag'):
        source=root/'shaders'/('depth_scene.'+stage);output=Path(temporary)/(stage+'.spv')
        subprocess.run([str(args.compiler),'-V','--target-env','vulkan1.0',str(source),'-o',str(output)],check=True)
        words=struct.unpack('<'+'I'*(output.stat().st_size//4),output.read_bytes())
        text+='// source-sha256: '+hashlib.sha256(source.read_bytes()).hexdigest()+'\ninline constexpr uint32_t depth_scene_'+stage+'_spv[]={\n'
        for i in range(0,len(words),8):text+='    '+','.join(hex(w) for w in words[i:i+8])+',\n'
        text+='};\n'
    (root/'src/depth_scene_spv.h').write_text(text,encoding='utf-8',newline='\n')
