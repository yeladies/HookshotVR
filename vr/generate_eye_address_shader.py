"""Regenerate the authored address-copy smoke shader; no game inputs."""
import argparse
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", required=True, help="Khronos glslang executable")
    parser.add_argument("--matrix-patch",action="store_true",help="Generate the authored GPU matrix-patch diagnostic instead")
    parser.add_argument("--root-alias-patch",action="store_true",help="Generate the authored full-table alias-patch GPU shader")
    args=parser.parse_args()
    if args.matrix_patch and args.root_alias_patch:parser.error("Select only one authored shader")
    root=Path(__file__).resolve().parent
    stem="eye_root_alias_patch" if args.root_alias_patch else ("eye_matrix_patch" if args.matrix_patch else "eye_address_copy")
    symbol="kEyeRootAliasPatchSpv" if args.root_alias_patch else ("kEyeMatrixPatchSpv" if args.matrix_patch else "kEyeAddressCopySpv")
    source=root/("shaders/"+stem+".comp")
    with tempfile.TemporaryDirectory(prefix="hookshot-vr-authored-spv-") as tmp:
        output=Path(tmp)/"copy.spv"
        subprocess.run([args.compiler,"-V","--target-env","vulkan1.2","-o",str(output),str(source)],check=True)
        data=output.read_bytes()
    if not data or len(data)%4 or len(data)>65536:
        raise RuntimeError("Unexpected bounded SPIR-V size")
    words=struct.unpack("<"+"I"*(len(data)//4),data)
    if words[0]!=0x07230203: raise RuntimeError("Invalid SPIR-V magic")
    digest=hashlib.sha256(source.read_bytes().replace(b"\r\n",b"\n")).hexdigest()
    text="// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by vr/generate_eye_address_shader.py; edit the authored .comp source.\n"
    text+="// Source SHA256: "+digest+"\n#pragma once\n#include <cstdint>\ninline constexpr uint32_t "+symbol+"[]={\n"
    text+="".join("    "+",".join(f"0x{w:08x}" for w in words[i:i+8])+",\n" for i in range(0,len(words),8))
    target=(root.parent/"gpu/vk/xr_root_alias_patch_spv.h" if args.root_alias_patch else (root.parent/"gpu/vk/xr_eye_matrix_patch_spv.h" if args.matrix_patch else root/("src/"+stem+"_spv.h")))
    target.write_text(text+"};\n",encoding="utf-8",newline="\n")
    if args.root_alias_patch:
        (root/"src/eye_root_alias_patch_spv.h").write_text('// SPDX-License-Identifier: GPL-3.0-or-later\n#pragma once\n#include "../../gpu/vk/xr_root_alias_patch_spv.h"\n',encoding="utf-8",newline="\n")
if __name__=="__main__": main()
